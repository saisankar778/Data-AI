"""Model guide (data dictionary) as Markdown: what each table, column and measure means."""

from __future__ import annotations

from datawright.connectors.powerbi.health import HealthReport
from datawright.connectors.powerbi.model import SemanticModel


def _cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def render_markdown(model: SemanticModel, report: HealthReport) -> str:
    lines = [
        f"# Model guide: {model.name}",
        "",
        f"{report.tables} tables, {report.columns} columns, {report.measures} measures. "
        f"Health score {report.score}/100 ({report.grade}); {report.ai_readiness}% of visible "
        f"objects documented ({report.documented}/{report.visible}).",
        "",
        "Generated by Datawright from model metadata. Objects marked *(hidden)* don't appear in "
        "the field list.",
        "",
    ]
    for t in sorted(model.tables.values(), key=lambda x: (x.is_hidden, x.name.lower())):
        if t.is_auto_date:
            continue
        hidden = " *(hidden)*" if t.is_hidden else ""
        lines += [f"## {t.name}{hidden}", "", t.description or "_No description yet._", ""]
        if t.measures:
            lines += ["**Measures**", "", "| Measure | Description | Format |", "|---|---|---|"]
            for m in sorted(t.measures, key=lambda x: x.name.lower()):
                name = m.name + (" *(hidden)*" if m.is_hidden else "")
                lines.append(
                    f"| {_cell(name)} | {_cell(m.description) or '—'} | "
                    f"{_cell(m.format_string) or '—'} |"
                )
            lines.append("")
        if t.columns:
            lines += ["**Columns**", "", "| Column | Type | Description |", "|---|---|---|"]
            for c in t.columns:
                name = (
                    c.name
                    + (" *(hidden)*" if c.is_hidden else "")
                    + (" *(key)*" if c.is_key else "")
                )
                lines.append(
                    f"| {_cell(name)} | {c.data_type or '?'} | {_cell(c.description) or '—'} |"
                )
            lines.append("")
        rels = [r for r in model.relationships if t.name == r.from_table]
        if rels:
            lines += ["**Relationships**", ""]
            for r in rels:
                notes = []
                if not r.is_active:
                    notes.append("inactive")
                if r.cross_filtering == "bothDirections":
                    notes.append("filters both ways")
                suffix = f" ({', '.join(notes)})" if notes else ""
                lines.append(f"- {r.label}, {r.from_cardinality} to {r.to_cardinality}{suffix}")
            lines.append("")
    measures = [(t, m) for t, m in model.all_measures() if m.expression.strip()]
    if measures:
        lines += ["## Appendix: measure definitions", ""]
        for t, m in sorted(measures, key=lambda x: (x[0].name.lower(), x[1].name.lower())):
            lines += [f"**{t.name}[{m.name}]**", "", "```dax", m.expression.strip(), "```", ""]
    return "\n".join(lines).rstrip() + "\n"
